    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
// 1. Validasi Input: Pastikan semua field terisi sebelum simpan
if (txtUID.getText().trim().isEmpty() || 
    txtKRID.getText().trim().isEmpty() || 
    txtKRName.getText().trim().isEmpty() || 
    txtKRDept.getSelectedItem() == null) {
    
    JOptionPane.showMessageDialog(this, "Mohon lengkapi semua data (UID, ID, Nama, dan Departemen)!", "Peringatan", JOptionPane.WARNING_MESSAGE);
    return;
}

try {
    // 2. Membuat objek Siswa dari input form
    Siswa s = new Siswa();
    s.setUidRfid(txtUID.getText().trim());
    s.setIdSiswa(txtKRID.getText().trim());
    s.setNamaLengkap(txtKRName.getText().trim());
    s.setDepartemen(txtKRDept.getSelectedItem().toString());

    // 3. Memanggil service untuk simpan ke MongoDB
    SiswaService service = new SiswaService();
    service.tambahSiswa(s);
    
    // 4. Notifikasi Berhasil
    JOptionPane.showMessageDialog(this, "Data Siswa Berhasil Disimpan!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
    
    // 5. REFRESH CARD: Memperbarui jPanel4 agar kartu baru muncul
    service.tampilSiswa(jPanel4, "");
    
    // 6. KOSONGKAN FORM: Agar siap untuk input data berikutnya
    resetForm(); 
    
    // 7. FOKUS KURSOR: Kembalikan ke field UID untuk scan RFID selanjutnya
    txtUID.requestFocus();
    
    // 8. UPDATE UI: Memastikan panel menggambar ulang kartu-kartu siswa
    jPanel4.revalidate();
    jPanel4.repaint();

} catch (Exception e) {
    // Menampilkan pesan error jika terjadi kegagalan sistem atau koneksi DB
    JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnSaveActionPerformed

