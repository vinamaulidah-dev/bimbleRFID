    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
try {
    // 1. Ambil data dari form
    Siswa s = new Siswa();
    s.setUidRfid(txtUID.getText().trim());
    s.setIdSiswa(txtKRID.getText().trim()); // Kunci utama untuk mencari data (idSiswa)
    s.setNamaLengkap(txtKRName.getText().trim());
    s.setDepartemen(txtKRDept.getSelectedItem().toString());

    // 2. Eksekusi Update
    SiswaService service = new SiswaService();
    service.updateSiswa(s);
    
    // 3. Notifikasi Sukses
    JOptionPane.showMessageDialog(this, "Data Berhasil Diperbarui!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
    
    // 4. REFRESH & RESET
    service.tampilSiswa(jPanel4, ""); // Gambar ulang kartu di UI
    resetForm(); // Kosongkan textfield
    
    // 5. Kembalikan kondisi tombol
    btnSave.setEnabled(true);
    btnUpdate.setEnabled(false);
    txtKRID.setEditable(true); // Aktifkan kembali ID jika sebelumnya dimatikan

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Gagal Update: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnUpdateActionPerformed

